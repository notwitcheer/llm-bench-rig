#!/usr/bin/env python3
"""Readout for item 77 (Nanbeige4.3-33B full pass). CPU only, idempotent, safe on a partial run; run it on capsule (python3, stdlib only).
Applies the PRE-REGISTERED rules from the item header exactly and writes ~/nanbeige43/readout.md + readout.json. Nothing is typed by hand.

usage: python3 nb_readout.py [--out DIR]
"""
import argparse
import glob
import json
import math
import os

R = os.environ.get("NB_R") or os.path.expanduser("~/benchmark-rig/results")   # NB_R / NB_AT_QWEN / NB_AT_NB: test knobs (synthetic trees), empty in production
AT_QWEN = os.environ.get("NB_AT_QWEN") or os.path.expanduser("~/agenttest-v2/results/c1")
AT_NB = os.environ.get("NB_AT_NB") or os.path.expanduser("~/agenttest-v2/results/nb43")
NB = {"q4": "nanbeige-nanbeige4-3-33b-q4-k-m", "q6": "nanbeige-nanbeige4-3-33b-q6-k"}
QW = {"q4": "qwen3-8-27b-q4-k-m", "q6": "qwen3-8-27b-q6-k", "iq3": "qwen3-8-27b-ud-iq3-xxs"}
TIE = {"q_avg": 1.2, "st_pts": 2.5, "gpqa_pts": 3.0, "aime_problems": 2, "agent_tasks": 3, "p": 0.05}


def jl(p):
    return [json.loads(x) for x in open(p) if x.strip()] if os.path.exists(p) else []


def jf(p):
    return json.load(open(p)) if os.path.exists(p) else None


def truth(v):
    return v is True or str(v).lower() == "true"


def mcnemar(a, b):
    keys = sorted(set(a) & set(b), key=str)
    n10 = sum(1 for k in keys if a[k] and not b[k])
    n01 = sum(1 for k in keys if b[k] and not a[k])
    n = n10 + n01
    p = 1.0 if n == 0 else min(1.0, 2 * sum(math.comb(n, i) for i in range(min(n10, n01) + 1)) / 2 ** n)
    return {"n": len(keys), "a_only": n10, "b_only": n01, "p": round(p, 4), "a_correct": sum(1 for k in keys if a[k]), "b_correct": sum(1 for k in keys if b[k])}


def tc_st(slug):
    return {r["id"]: r.get("outcome") == "correct" for r in jl(f"{R}/toolcall-v1/{slug}-st-on/items.jsonl")}, jf(f"{R}/toolcall-v1/{slug}-st-on/summary.json")


def tc_s5(slug):
    return {r["id"]: r.get("outcome") == "correct" for r in jl(f"{R}/toolcall-v1/{slug}-s5-on/multi_turn.jsonl")}, jf(f"{R}/toolcall-v1/{slug}-s5-on/summary.json")


def gpqa(d):
    p = jf(f"{R}/{d}/gpqa_progress.json")
    gj = jf(f"{R}/{d}/gpqa.json")
    tk = jl(f"{R}/{d}/gpqa_tokens.jsonl")
    if gj is not None and gj.get("capped_rate") is None and tk:
        gj = dict(gj, capped_rate=round(sum(1 for x in tk if x.get("capped")) / len(tk), 4), capped_rate_source="gpqa_tokens.jsonl sidecar")
    return ({k: truth(v.get("correct")) for k, v in p["completed"].items()} if p else {}), gj


def aime(d):
    p = jf(f"{R}/{d}/ma_aime_2026_progress.json")
    return ({k: truth(v.get("correct")) for k, v in p["completed"].items()} if p else {}), jf(f"{R}/{d}/ma_aime_2026_detail.json")


def agent(slug, root):
    s = jf(f"{root}/{slug}/summary.json")
    return ({k: bool(v[0]) for k, v in s["per_task"].items()} if s else {}), s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.expanduser("~/nanbeige43"))
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    L, J = ["# Nanbeige4.3-33B full pass: readout (generated by nb_readout.py, every number read from result files)", ""], {}

    # ---- fit
    L += ["## context ceiling (fit leg, board build b10371, own server per point, ~6k prefill)", "", "| file | KV | ceiling ctx | first fail | loaded MiB / peak MiB at the ceiling |", "|---|---|---:|---:|---|"]
    fit = {}
    for k, slug in NB.items():
        for kv in ("f16", "q8_0"):
            f = jf(f"{R}/{slug}/fit/fit-{kv}.json")
            fit[(k, kv)] = f
            if not f:
                L.append(f"| {k} | {kv} | not run | | |")
                continue
            c = f.get("ceiling_ctx")
            pt = (f.get("points") or {}).get(str(c), {}) if c else {}
            L.append(f"| {k} | {kv} | {c} | {f.get('first_fail_ctx')} | {pt.get('vram_loaded_mib')} / {pt.get('vram_peak_mib')} |")
    J["fit"] = {f"{k}_{kv}": (v or {}).get("ceiling_ctx") for (k, kv), v in fit.items()}

    # ---- speed + board
    L += ["", "## speed (llama-bench, board build) and the five-task board (think-off, sample 0.5)", "",
          "| row | tg128 | pp512 | tg128 @d8192 | tg128 @d32768 | VRAM peak MiB | KV of the pass | mmlu | arc | hellaswag | humaneval | gsm8k | q_avg |", "|---|---:|---:|---:|---:|---:|---|---:|---:|---:|---:|---:|---:|"]
    qavg = {}
    for lab, d in [("Nanbeige Q4_K_M", NB["q4"]), ("Qwen3.8-27B Q4_K_M", QW["q4"]), ("Nanbeige Q6_K", NB["q6"]), ("Qwen3.8-27B Q6_K", QW["q6"])]:
        sp, ql = jf(f"{R}/{d}/speed.json") or {}, jf(f"{R}/{d}/quality.json") or {}
        sc = [(ql.get(t) or {}).get("score") for t in ("mmlu", "arc_challenge", "hellaswag", "humaneval", "gsm8k")]
        qa = round(sum(sc) / 5, 2) if all(x is not None for x in sc) else None
        qavg[d] = qa
        g = lambda k: (sp.get(k) or {}).get("tokens_per_sec")  # noqa: E731
        L.append(f"| {lab} | {g('tg128')} | {g('pp512')} | {g('tg128@d8192')} | {g('tg128@d32768')} | {sp.get('vram_peak_mib')} | {sp.get('kv', 'f16')} | " + " | ".join(str(x) for x in sc) + f" | {qa} |")
    J["q_avg"] = qavg
    for k in ("q4", "q6"):
        n, q = qavg.get(NB[k]), qavg.get(QW[k])
        if n is not None and q is not None:
            L.append(f"- {k}: Nanbeige q_avg {n} vs Qwen {q}, delta {n - q:+.2f}, {'TIE' if abs(n - q) < TIE['q_avg'] else ('Nanbeige ahead' if n > q else 'Qwen ahead')} (margin {TIE['q_avg']})")

    # ---- toolcall
    L += ["", "## toolcall-v1 (BFCL v4 slice, raw mode, think-on, greedy, frozen ids, parser-2)", "", "| row | single-turn correct /906 (set-weighted, as the 10-25 readout; pairing uses the 899 unique ids) | S5 multi-turn /100 | capped | python_bool replies |", "|---|---:|---:|---:|---:|"]
    tc = {}
    for lab, d in [("Nanbeige Q4_K_M", NB["q4"]), ("Nanbeige Q6_K", NB["q6"]), ("Qwen3.8-27B Q6_K", QW["q6"]), ("Qwen3.8-27B UD-IQ3_XXS", QW["iq3"])]:
        st, ss = tc_st(d)
        s5, s5s = tc_s5(d)
        tc[d] = (st, s5)
        pace = (ss or {}).get("single_turn_pace") or {}
        stn = (sum((ss["single_turn"].get(x) or {}).get("correct", 0) for x in ("S1", "S2", "S3", "S4")), 906) if ss else (sum(st.values()), len(st))
        L.append(f"| {lab} | {stn[0]}/{stn[1]}{'' if ss else ' (partial)'} | {sum(s5.values())}/{len(s5)}{'' if s5s else ' (partial)'} | {pace.get('capped')} | {pace.get('python_bool_replies')} |")
    paired = {}
    for k in ("q4", "q6"):
        for cmp_k in ("q6", "iq3"):
            if k == "q4" and cmp_k == "iq3":
                continue
            for name, i in (("st-on", 0), ("s5-on", 1)):
                m = mcnemar(tc[NB[k]][i], tc[QW[cmp_k]][i])
                paired[f"tc_{name}_nb{k}_vs_qwen{cmp_k}"] = m
                L.append(f"- paired {name}, Nanbeige {k} vs Qwen {cmp_k}: {m['a_correct']} vs {m['b_correct']} on {m['n']} common ids, discordant {m['a_only']} / {m['b_only']}, exact p {m['p']}")
    nbq = mcnemar(tc[NB["q4"]][1], tc[NB["q6"]][1])
    paired["tc_s5_nbq4_vs_nbq6"] = nbq
    L.append(f"- paired S5, Nanbeige Q4_K_M vs Nanbeige Q6_K (which-file): {nbq['a_correct']} vs {nbq['b_correct']}, discordant {nbq['a_only']} / {nbq['b_only']}, p {nbq['p']}")

    # ---- agenttest
    L += ["", "## agenttest v2 (30 frozen tasks, real Hermes sessions, -c 65536, card sampling)", "", "| row | file / KV | pass /30 | A | B | C | blocks | other errs | wall min | peak MiB | decode p50 | NOFIT reason |", "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|"]
    ag = {}
    rows = [(s, AT_NB) for s in ("nanbeige43-33b-q4km-f16", "nanbeige43-33b-q4km-q8kv", "nanbeige43-33b-q6k-f16", "nanbeige43-33b-q6k-q8kv")] + [(s, AT_QWEN) for s in ("qwen38-27b-ud-q4km", "qwen38-27b-q6k", "qwen38-27b-ud-iq3xxs")]
    for s, root in rows:
        pt, sm = agent(s, root)
        nf = jf(f"{root}/{s}/load-failed.json")
        if nf:
            L.append(f"| {s} | | NOFIT | | | | | | | | | {nf.get('reason')} |")
            ag[s] = None
            continue
        if not sm:
            continue
        ag[s] = pt
        g = sm.get("by_group") or {}
        tim = jf(f"{root}/{s}/server-timings.json") or {}
        L.append(f"| {s} | | {sm['passed']} | {g.get('diff:A')} | {g.get('diff:B')} | {g.get('diff:C')} | {sm.get('approval_blocks')} | {sm.get('tool_errors_other')} | {sm['wall_s_total'] / 60:.0f} | {sm.get('vram_peak_mib')} | {(tim.get('decode_tps_requests_ge32tok') or {}).get('p50')} | |")
    for nbrow in ("nanbeige43-33b-q4km-q8kv", "nanbeige43-33b-q4km-f16", "nanbeige43-33b-q6k-q8kv", "nanbeige43-33b-q6k-f16"):
        for q in ("qwen38-27b-ud-q4km", "qwen38-27b-q6k"):
            if ag.get(nbrow) and ag.get(q):
                m = mcnemar(ag[nbrow], ag[q])
                paired[f"agent_{nbrow}_vs_{q}"] = m
                L.append(f"- paired agenttest {nbrow} vs {q}: {m['a_correct']} vs {m['b_correct']}, discordant {m['a_only']} / {m['b_only']}, p {m['p']}, lead {m['a_correct'] - m['b_correct']:+d} (tie under {TIE['agent_tasks']} tasks)")

    # ---- GPQA think-on + AIME
    L += ["", "## GPQA-diamond think-on (second tier, never folded into q_avg) and AIME 2026 at 32k", "", "| row | GPQA think-on | capped_rate | parse failures | AIME 2026 32k | capped_rate | parse failures |", "|---|---:|---:|---:|---:|---:|---:|"]
    gq, am = {}, {}
    for lab, g_d, a_d in [("Nanbeige Q4_K_M", f"{NB['q4']}-thinkon", f"{NB['q4']}-matharena-32k"), ("Nanbeige Q6_K", f"{NB['q6']}-thinkon", f"{NB['q6']}-matharena-32k"),
                          ("Qwen3.8-27B Q6_K", "qwen3-8-27b-q6-k-thinkon-rerun", "qwen3-8-27b-q6-k-matharena-32k"), ("Qwen3.8-27B UD-IQ3_XXS", "qwen3-8-27b-ud-iq3-xxs-thinkon", "qwen3-8-27b-ud-iq3-xxs-matharena-32k")]:
        gp, gj = gpqa(g_d)
        ap_, aj = aime(a_d)
        gq[lab], am[lab] = gp, ap_
        L.append(f"| {lab} | {(gj or {}).get('score')} ({sum(gp.values())}/{len(gp)}) | {(gj or {}).get('capped_rate')} | {(gj or {}).get('parse_failures')} | {(aj or {}).get('score')} ({sum(ap_.values())}/{len(ap_)}) | {(aj or {}).get('capped_rate')} | {(aj or {}).get('parse_failures')} |")
    for lab in ("Nanbeige Q4_K_M", "Nanbeige Q6_K"):
        for q in ("Qwen3.8-27B Q6_K", "Qwen3.8-27B UD-IQ3_XXS"):
            if gq.get(lab) and gq.get(q):
                m = mcnemar(gq[lab], gq[q])
                paired[f"gpqa_{lab}_vs_{q}"] = m
                L.append(f"- paired GPQA think-on, {lab} vs {q}: {m['a_correct']} vs {m['b_correct']}, discordant {m['a_only']} / {m['b_only']}, p {m['p']}")
            if am.get(lab) and am.get(q):
                m = mcnemar(am[lab], am[q])
                paired[f"aime_{lab}_vs_{q}"] = m
                L.append(f"- paired AIME, {lab} vs {q}: {m['a_correct']} vs {m['b_correct']}, discordant {m['a_only']} / {m['b_only']}, p {m['p']}")
    L.append("- label: the card's GPQA 89.5 / AIME 2026 95.2 are at the highest thinking effort with an unlimited budget and sampling; ours are greedy at 16k (GPQA) / 32k (AIME) caps, so a gap to the card is a budget-and-sampling difference first.")

    # ---- line-1 rule (pre-registered)
    L += ["", "## line 1 (rule A, pre-registered in the item header)", ""]
    best = None
    for k in ("q6", "q4"):
        s5 = tc[NB[k]][1]
        if len(s5) == 100:
            best = best or k
    A = "A: not decidable yet (no complete Nanbeige S5 leg)"
    if best:
        mm = paired.get(f"tc_s5-on_nb{best}_vs_qwenq6")
        if mm:
            n, q = mm["a_correct"], mm["b_correct"]
            verdict = "wins" if (n > q and mm["p"] < TIE["p"]) else ("loses" if (q > n and mm["p"] < TIE["p"]) else "ties")
            st_n, st_q = sum(tc[NB[best]][0].values()), sum(tc[QW["q6"]][0].values())
            stn = len(tc[NB[best]][0])
            dst = (st_n / stn - st_q / len(tc[QW["q6"]][0])) * 100 if stn else 0   # unique-id basis (899)
            A = (f"A ({verdict}): \"claims to beat Qwen3.8-27B; on Hermes Agent tool calls on one 5090 it {verdict} {n} vs {q} (Nanbeige {best.upper()} vs Qwen Q6_K, S5 multi-turn, "
                 f"discordant {mm['a_only']}/{mm['b_only']}, exact p {mm['p']}); single-turn {st_n}/{stn} vs {st_q}/{len(tc[QW['q6']][0])} ({dst:+.1f} pts, tie margin {TIE['st_pts']})\"")
    L.append(A)
    J["line1"] = A
    J["paired"] = paired
    open(os.path.join(a.out, "readout.md"), "w").write("\n".join(L) + "\n")
    json.dump(J, open(os.path.join(a.out, "readout.json"), "w"), indent=1)
    print("\n".join(L))


if __name__ == "__main__":
    main()
